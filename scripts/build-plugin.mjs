import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const files = ['aliases.js', 'content-json.js', 'transform.js', 'plugin.js'];
const parts = await Promise.all(files.map(async name => {
  let source = await readFile(new URL(`src/${name}`, root), 'utf8');
  source = source.replace(/^import\b[^;]*;\r?\n/gm, '');
  if (name !== 'plugin.js') source = source.replace(/^export /gm, '');
  return `// --- ${name} ---\n${source.trim()}\n`;
}));

await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/newapi-fc.plugin.js', root),
  '// Generated by scripts/build-plugin.mjs. Edit src/ and rebuild.\n\n' + parts.join('\n'));
console.log('Built dist/newapi-fc.plugin.js');
